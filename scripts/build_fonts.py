"""Check the font library and write what is generated from its registry.

    env/bin/python apps/report_view/scripts/build_fonts.py          # from the bench root

``report_view/fonts.json`` is the one registry of the fonts in ``report_view/public/fonts``
(core/fonts.py). This script checks every entry (names, categories, every file it names
exists and is a font, a licence file beside it) and writes:

- ``report_view/public/css/rv_fonts.css``: the ``@font-face`` of every face (``font-display:
  swap``; woff2, then TrueType for wkhtmltopdf), loaded in Desk by ``app_include_css``;
- ``report_view/public/fonts/README.md``: every family, its licence and source, and the fonts
  of frappe_jodit_editor that were left out and why.

A development script: the app never imports it. Run it again after editing the registry and
commit its output.
"""

import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..", "report_view")
CSS_OUT = os.path.join(PKG, "public", "css", "rv_fonts.css")
README_OUT = os.path.join(PKG, "public", "fonts", "README.md")

# core/fonts.py reads its constants from report_view/letterhead_contract.json (core/contract.py)
sys.path.insert(0, os.path.join(HERE, ".."))
_spec = importlib.util.spec_from_file_location("rv_fonts", os.path.join(PKG, "core", "fonts.py"))
fonts = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(fonts)

FAMILY = re.compile(r"^[A-Za-z0-9 ]{2,60}$")
SLUG = re.compile(r"^[a-z0-9-]{2,40}$")
LICENCE_FILES = ("OFL.txt", "COPYING", "LICENSE")
MAGIC = {"ttf": (b"\x00\x01\x00\x00", b"true", b"OTTO"), "woff2": (b"wOF2",)}

EXCLUDED = [
	(
		"B Badr, B Baran, B Bardiya, B Compset, B Davat, B Elham, B Esfehan, B Fantezy, B Farnaz, "
		"B Ferdosi, B Hamid, B Helal, B Homa, B Jadid, B Jalal, B Koodak, B Kourosh, B Lotus, B Mahsa, "
		"B Mehr, B Mitra, B Morvarid, B Narm, B Nasim, B Nazanin, B Roya, B Setareh, B Shiraz, "
		"B Tabassom, B Tehran, B Titr, B Traffic, B Vahid, B Yagut, B Yas, B Yekan, B Zar, B Ziba "
		"(the «B …» series)",
		"© 2000 Borna Rayaneh, no licence to redistribute.",
	),
	("B Sina", "«MRT Magic Pack» (Win2Farsi, Mohammad Reza Tavakoli): no licence to redistribute."),
	("B Titr TG E", "© 2009 Reza Teimouri-Neda Studio: no licence to redistribute."),
	("DecoType Naskh Variants", "© DecoType, shipped with Microsoft Office: not redistributable."),
	("PT Bold Heading", "Designed for Microsoft Corp. by Platinum Inc.: not redistributable."),
	(
		"Iranian Sans (IranianSans.*, irsans.ttf)",
		"© 2006 Nevisa, all rights reserved: no licence to redistribute.",
	),
]


def fail(msg):
	sys.exit(f"build_fonts: {msg}")


def check():
	seen_family, seen_slug = set(), set()
	for e in fonts.registry():
		fam, slug = e.get("family"), e.get("slug")
		if not isinstance(fam, str) or not FAMILY.match(fam) or fam in seen_family:
			fail(f"bad or repeated family {fam!r}")
		if not isinstance(slug, str) or not SLUG.match(slug) or slug in seen_slug:
			fail(f"bad or repeated slug {slug!r}")
		seen_family.add(fam)
		seen_slug.add(slug)
		if e.get("category") not in fonts.CATEGORIES:
			fail(f"{fam}: unknown category {e.get('category')!r}")
		if not e.get("scripts") or any(s not in fonts.SCRIPTS for s in e["scripts"]):
			fail(f"{fam}: bad scripts {e.get('scripts')!r}")
		if not e.get("licence") or not e.get("source"):
			fail(f"{fam}: licence and source are required")
		faces = list(fonts.font_files(e))
		if e.get("system"):
			if faces:
				fail(f"{fam}: a system font ships no file")
			continue
		if "400" not in e.get("weights", {}) and not faces:
			fail(f"{fam}: no face")
		folder = os.path.join(fonts.FONTS_DIR, slug)
		if not any(os.path.isfile(os.path.join(folder, n)) for n in LICENCE_FILES):
			fail(f"{fam}: no licence file in {slug}/")
		for _style, weight, files in faces:
			if weight not in (100, 200, 300, 400, 500, 600, 700, 800, 900) or not files.get("ttf"):
				fail(f"{fam}: weight {weight} needs a TrueType file")
			for fmt, rel in files.items():
				if fmt not in MAGIC or not rel.startswith(slug + "/") or ".." in rel:
					fail(f"{fam}: bad file {rel!r}")
				path = os.path.join(fonts.FONTS_DIR, rel)
				if not os.path.isfile(path):
					fail(f"{fam}: missing {rel}")
				with open(path, "rb") as f:
					if not f.read(4).startswith(MAGIC[fmt]):
						fail(f"{fam}: {rel} is not a {fmt} font")


def write_css():
	head = (
		"/* Generated by scripts/build_fonts.py from report_view/fonts.json: do not edit.\n"
		"   The font library of Report View (public/fonts/README.md for the licences). A file is\n"
		"   fetched only when a page uses its family; woff2 for browsers, TrueType for wkhtmltopdf. */\n"
	)
	body = "\n".join(fonts.font_face_css(e["family"]) for e in fonts.registry() if not e.get("system"))
	css = head + body.replace("}@font-face", "}\n@font-face") + "\n"
	with open(CSS_OUT, "w", encoding="utf-8") as f:
		f.write(css)


def write_readme():
	rows = []
	for e in fonts.registry():
		weights = ", ".join(sorted(e.get("weights", {}))) + (" (+ italic)" if e.get("italic") else "")
		formats = (
			"system"
			if e.get("system")
			else (
				"woff2 + ttf" if any("woff2" in f for _s, _w, f in fonts.font_files(e)) else "ttf (unchanged)"
			)
		)
		rows.append(
			f"| {e['family']} | `{e['slug']}` | {e['category']} | {', '.join(e['scripts'])} | {weights or '—'} | {formats} | {e['licence']} | {e['source']} |"
		)
	text = f"""# Report View font library

Generated by `scripts/build_fonts.py` from `report_view/fonts.json` — do not edit by hand.

Every font here may be redistributed with the app. Each folder carries its licence:
`OFL.txt` (SIL Open Font License 1.1), or `COPYING` (GNU GPL v2) with `NEWS` (the FarsiWeb
distribution terms) and `LICENSE` (the licence text the font carries in its own name table).

- **OFL fonts** come from the official [google/fonts](https://github.com/google/fonts/tree/main/ofl)
  repository. A variable font was cut into static instances (fontTools `varLib.instancer`) —
  allowed by the OFL for families without a Reserved Font Name on the name they keep. Source
  Serif 4 («Source») and Merriweather («Merriweather») reserve their names, so their upstream
  static TrueType files ship unchanged. The woff2 files are the same fonts compressed (fontTools).
- **FarsiWeb fonts** (Sharif FarsiWeb FarsiFonts 0.4) and **FreeFarsi** (Abbas Izad) come from
  `frappe_jodit_editor/public/fonts`. Homa, Nazli, Titr and FreeFarsi are GPL: they also ship
  as woff2. Elham, Koodak, Roya and Terafik may be redistributed only unchanged: they ship as
  their original TrueType files, byte for byte.
- **DejaVu Sans** is installed on the server and is not shipped.

Total: {len(fonts.registry())} families. Paths below are relative to `/assets/report_view/fonts/`.

| Family | Folder | Category | Scripts | Weights | Files | Licence | Source |
|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}

## Left out (fonts of frappe_jodit_editor that may not be redistributed)

| Font | Reason |
|---|---|
{chr(10).join(f"| {name} | {why} |" for name, why in EXCLUDED)}
"""
	with open(README_OUT, "w", encoding="utf-8") as f:
		f.write(text)


if __name__ == "__main__":
	check()
	write_css()
	write_readme()
	print(
		f"build_fonts: {len(fonts.registry())} families; wrote {os.path.relpath(CSS_OUT)} and {os.path.relpath(README_OUT)}"
	)
